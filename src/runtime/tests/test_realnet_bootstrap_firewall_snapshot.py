import pytest

from tools.realnet_bootstrap_smoke import firewall_invariant_lines


BEFORE='''# Generated by iptables-save v1.8.11 (nf_tables) on Tue Oct 13 15:04:09 2026
*filter
:INPUT ACCEPT [0:0]
:FORWARD ACCEPT [0:0]
:OUTPUT ACCEPT [0:0]
-A FORWARD -i br-test -m comment --comment owned -j ACCEPT
-A FORWARD -o br-test -m comment --comment owned -j ACCEPT
COMMIT
# Completed on Tue Oct 13 15:04:09 2026'''


def test_only_metadata_timestamps_may_change():
    after=BEFORE.replace('15:04:09','15:04:11')
    assert firewall_invariant_lines(BEFORE)==firewall_invariant_lines(after)
    assert '15:04:09' in BEFORE and '15:04:11' in after


@pytest.mark.parametrize('old,new',[
    ('-j ACCEPT','-j DROP'),
    ('-i br-test','-i foreign'),
    ('--comment owned','--comment foreign'),
    (':FORWARD ACCEPT',':FORWARD DROP'),
    ('[0:0]','[1:20]'),
    ('*filter','*nat'),
    ('COMMIT',''),
    ('v1.8.11','v1.8.12'),
    ('nf_tables','legacy'),
    ('Tue Oct 13 15:04:09 2026','invalid timestamp'),
    ('Tue Oct 13 15:04:09 2026','Tue Oct 99 15:04:09 2026'),
    ('Tue Oct 13 15:04:09 2026','Tue Oct 13 99:04:09 2026'),
])
def test_every_other_field_or_invalid_timestamp_remains_checked(old,new):
    assert firewall_invariant_lines(BEFORE)!=firewall_invariant_lines(BEFORE.replace(old,new))


@pytest.mark.parametrize('change',['order','duplicate','missing_header','missing_footer','unknown_comment','timestamp_inside_rules','metadata_wrong_position'])
def test_rule_and_metadata_structure_remains_checked(change):
    lines=BEFORE.splitlines()
    if change=='order':lines[5],lines[6]=lines[6],lines[5]
    if change=='duplicate':lines.insert(5,lines[5])
    if change=='missing_header':lines.pop(0)
    if change=='missing_footer':lines.pop()
    if change=='unknown_comment':lines.insert(2,'# foreign metadata')
    if change=='timestamp_inside_rules':lines.insert(5,'# Completed on Tue Oct 13 15:04:11 2026')
    if change=='metadata_wrong_position':lines[0],lines[1]=lines[1],lines[0]
    assert firewall_invariant_lines(BEFORE)!=firewall_invariant_lines('\n'.join(lines))
