def command(args):
    result=subprocess.run(args,text=True,capture_output=True,timeout=40)
    if result.returncode:raise RuntimeError('fixture command failed: '+shlex.join(args[:5])+' '+result.stderr.strip())
    return result.stdout.strip()


def firewall_invariant_lines(snapshot):
    """Keep all content except valid timestamps at the two metadata positions."""
    lines=snapshot.splitlines()
    patterns=((0,r'(# Generated by iptables-save v[0-9]+\.[0-9]+\.[0-9]+ \((?:nf_tables|legacy)\) on )(.+)'),
              (-1,r'(# Completed on )(.+)'))
    for index,pattern in patterns:
        if not lines:break
        match=re.fullmatch(pattern,lines[index])
        if not match:continue
        try:datetime.strptime(match[2],'%a %b %d %H:%M:%S %Y')
        except ValueError:continue
        lines[index]=match[1]+'<timestamp>'
    return lines


def retry_invariant_differences(before,after):
    """Ignore only elapsed time on the same owned veth bridge port."""
    differences=snapshot_differences(before,after)
    left=before.get('host',{});right=after.get('host',{})
    identity=('ifname','ifindex','address','ifalias','link_index','master')
    same_port=all(key in left and key in right and left[key]==right[key] for key in identity)
    infos=[value.get('linkinfo',{}) for value in (left,right)]
    same_port=same_port and all(info.get('info_kind')=='veth' and info.get('info_slave_kind')=='bridge' for info in infos)
    def elapsed_timer(difference):
        return (same_port and difference['path']=='snapshot.host.linkinfo.info_slave_data.forward_delay_timer'
                and all(type(difference.get(key)) in (int,float) and math.isfinite(difference[key])
                        and difference[key]>=0 for key in ('expected','actual')))
    return [difference for difference in differences if not elapsed_timer(difference)]


